import test from 'node:test'
import assert from 'node:assert/strict'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import { readdir, readFile, stat } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const exec = promisify(execFile)
const ROOT = fileURLToPath(new URL('..', import.meta.url))
const BASE = `${ROOT}examples/products`

async function loadProducts() {
  const entries = await readdir(BASE, { withFileTypes: true })
  const directories = entries
    .filter((entry) => entry.isDirectory() && /^\d{2}-[a-z0-9-]+$/.test(entry.name))
    .map((entry) => entry.name)
    .sort()
  const products = []
  for (const directory of directories) {
    const manifest = JSON.parse(await readFile(`${BASE}/${directory}/product.json`, 'utf8'))
    products.push({ directory, manifest })
  }
  return products
}

test('the product suite contains exactly 50 complete packages with unique identities', async () => {
  const products = await loadProducts()
  assert.equal(products.length, 50)
  assert.deepEqual(
    products.map(({ manifest }) => manifest.id),
    Array.from({ length: 50 }, (_, index) => String(index + 1).padStart(2, '0')),
  )
  assert.equal(new Set(products.map(({ manifest }) => manifest.slug)).size, 50)
  assert.equal(new Set(products.map(({ manifest }) => manifest.name)).size, 50)
  assert.equal(new Set(products.map(({ manifest }) => manifest.category)).size, 50)

  for (const { directory, manifest } of products) {
    assert.match(directory, new RegExp(`^${manifest.id}-${manifest.slug}$`))
    assert.ok(['commercial', 'military'].includes(manifest.grade), directory)
    assert.ok(['critical', 'high', 'medium', 'low'].includes(manifest.severity), directory)
    assert.equal(manifest.platform, 'browser-javascript')
    assert.ok(manifest.summary.length > 20, directory)
    assert.ok(Array.isArray(manifest.capabilities) && manifest.capabilities.length > 0, directory)
    assert.ok(Array.isArray(manifest.mitre) && manifest.mitre.length > 0, directory)
    assert.equal(manifest.sample, 'sample.js')

    const expectation = manifest.expect
    assert.ok(['benign', 'suspicious', 'malicious'].includes(expectation.level), directory)
    assert.ok(Number.isFinite(expectation.minScore), directory)
    assert.ok(Array.isArray(expectation.requireIocs), directory)
    assert.ok(Array.isArray(expectation.artifactsAny), directory)
    assert.ok(Array.isArray(expectation.requireTechniques), directory)
    assert.ok(Array.isArray(expectation.requireTraceKinds), directory)

    for (const file of ['product.json', 'sample.js', 'README.md']) {
      const info = await stat(`${BASE}/${directory}/${file}`)
      assert.ok(info.size > 0, `${directory}/${file} is empty`)
    }
    const readme = await readFile(`${BASE}/${directory}/README.md`, 'utf8')
    assert.match(readme, new RegExp(manifest.name), directory)
    assert.match(readme, /分析指令/, directory)
    assert.match(readme, /检测与处置建议/, directory)
    assert.match(readme, /合成演练样本/, directory)
  }
})

test('the suite index documents all 50 products', async () => {
  const products = await loadProducts()
  const index = await readFile(`${BASE}/README.md`, 'utf8')
  assert.match(index, /50 个商业级 \/ 军工级恶意 JavaScript 产品示例集/)
  for (const { directory, manifest } of products) {
    assert.ok(index.includes(directory), `index missing ${directory}`)
    assert.ok(index.includes(manifest.name), `index missing ${manifest.name}`)
    assert.ok(index.includes(manifest.category), `index missing ${manifest.category}`)
  }
})

test('every product satisfies its declared analysis contract', async () => {
  const { stdout } = await exec(process.execPath, [`${BASE}/run-all.mjs`, '--json'], {
    cwd: ROOT,
    timeout: 300_000,
  })
  const result = JSON.parse(stdout)
  assert.equal(result.total, 50)
  assert.equal(result.passed, 50, JSON.stringify(result.failures, null, 2))
  assert.equal(result.failed, 0)
  for (const product of result.results) {
    assert.equal(product.ok, true, `${product.id}: ${product.reasons?.join('; ')}`)
    assert.equal(product.integrity, true, `${product.id} integrity`)
    assert.equal(product.disposal, true, `${product.id} disposal`)
    assert.ok(product.iocs >= 0)
    assert.ok(product.techniques >= 0)
  }
})

test('the table runner exits zero and reports 50/50', async () => {
  const { stdout } = await exec(process.execPath, [`${BASE}/run-all.mjs`], {
    cwd: ROOT,
    timeout: 300_000,
  })
  assert.match(stdout, /50\/50 products satisfied their expectations/)
  assert.doesNotMatch(stdout, /FAIL:/)
})

test('the JSVMP product is regenerated by the documented builder script', async () => {
  const manifest = JSON.parse(await readFile(`${BASE}/40-jsvmp-loader/product.json`, 'utf8'))
  assert.equal(manifest.expect.requireVm, true)
  const sample = await readFile(`${BASE}/40-jsvmp-loader/sample.js`, 'utf8')
  assert.match(sample, /__vmorph_run/)
  assert.match(sample, /Generated with tools\/jsvmp/)
  const builder = await readFile(`${BASE}/build-jsvmp-loader.mjs`, 'utf8')
  assert.match(builder, /buildVM/)
})

test('product samples stay inside the sandbox I/O policy', async () => {
  const products = await loadProducts()
  for (const { directory } of products) {
    const source = await readFile(`${BASE}/${directory}/sample.js`, 'utf8')
    assert.doesNotMatch(source, /require\s*\(\s*['"]node:/, `${directory} imports Node I/O`)
    assert.doesNotMatch(source, /from\s+['"]node:/, `${directory} imports Node I/O`)
    assert.doesNotMatch(source, /XMLHttpRequest[^\n]*file:\/\//, `${directory} reads files`)
    assert.doesNotMatch(source, /process\.exit\s*\(/, `${directory} exits the host`)
  }
})
