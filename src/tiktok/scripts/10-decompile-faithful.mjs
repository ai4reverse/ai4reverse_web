#!/usr/bin/env node
/**
 * Faithful decompilation: inline every handler with its real operands.
 *
 * The semantic table in output/opcode-table.md is readable but interpretive — a
 * worker's one-line `js` glosss can misname which operand is the destination.
 * This pass removes the interpretation entirely: it takes the handler source
 * for each opcode, replaces `J(n)` / `L(n)` / `K(n)` with the literal values
 * that instruction actually carries, and renames the VM state to `vm`.
 *
 * What comes out is behaviourally identical to what the interpreter would run
 * for that instruction, which makes it the artifact to check other claims
 * against. It is verbose on purpose: verbosity that can be audited beats
 * brevity that cannot.
 *
 * Emits output/decompiled-faithful.js.
 *
 *   node scripts/10-decompile-faithful.mjs
 */

import fs from 'node:fs'
import path from 'node:path'
import { parse } from '@babel/parser'
import _generate from '@babel/generator'
import _traverse from '@babel/traverse'

const generate = _generate.default ?? _generate
const traverse = _traverse.default ?? _traverse

const ROOT = path.resolve(import.meta.dirname, '..')
const TMP = path.join(ROOT, 'tmp')
const OUT = path.join(ROOT, 'output')

const disasm = JSON.parse(fs.readFileSync(path.join(TMP, 'disasm.json'), 'utf8'))
const fnDoc = JSON.parse(fs.readFileSync(path.join(TMP, 'functions.json'), 'utf8'))
const table = JSON.parse(fs.readFileSync(path.join(TMP, 'opcode-table.json'), 'utf8'))
const byOpcode = new Map(table.opcodes.map((o) => [o.opcode, o]))

const instructions = disasm.instructions

// --- pre-render each opcode's handler once ---------------------------------
const handlerBody = new Map()

/**
 * The VM state parameter of a handler.
 *
 * Almost every handler names it `n`, but 0073, 0075, 0127 and 0357 name it `t`.
 * Reading it from the source instead of assuming `n` is what makes those
 * instructions executable.
 */
const handlerParam = new Map()
function handlerParamName(opcode) {
  if (handlerParam.has(opcode)) return handlerParam.get(opcode)
  const raw = fs.readFileSync(path.join(TMP, 'handlers', String(opcode).padStart(4, '0') + '.js'), 'utf8')
  const m = raw.match(/function\s*\(\s*([A-Za-z_$][\w$]*)/)
  const name = m ? m[1] : 'n'
  handlerParam.set(opcode, name)
  return name
}

function loadHandler(opcode) {
  if (handlerBody.has(opcode)) return handlerBody.get(opcode)
  const file = path.join(TMP, 'handlers', String(opcode).padStart(4, '0') + '.js')
  const raw = fs.readFileSync(file, 'utf8')
  const body = raw
    .split('\n')
    .filter((l) => !l.startsWith('//'))
    .join('\n')
    .trim()
  const expr = parse(`(${body})`, { sourceType: 'script' }).program.body[0].expression
  const code = generate(expr, { compact: true, concise: true, comments: false }).code
  handlerBody.set(opcode, code)
  return code
}

/**
 * Render one instruction's handler with operands substituted.
 *
 * Substitution is textual and order-based: the generated handler body contains
 * `J(n)` / `L(n)` / `K(n)` in exactly the order the interpreter consumes the
 * byte stream, so the Nth reader call gets the Nth operand. The original
 * parameter name `n` is deliberately kept — renaming it to `vm` would break the
 * nested closures, which rebind `n` as their own parameter.
 */
function renderInstruction(ins) {
  const code = loadHandler(ins.opcode)
  // The VM parameter is usually `n`, but handlers 0073, 0075, 0127 and 0357
  // name it `t`. Keying the substitution on the handler's own parameter is what
  // makes those 37 instructions executable at all.
  const param = handlerParamName(ins.opcode)
  let operandIndex = 0
  return code.replace(new RegExp(`\\b[JLK]\\(${param}\\)`, 'g'), () => {
    const value = ins.operands[operandIndex++]
    return value === undefined ? 'undefined' : String(value)
  })
}

// --- emit -------------------------------------------------------------------
const out = []
out.push('/*')
out.push(' * Faithful decompilation — every instruction inlined with its real operands.')
out.push(' *')
out.push(' * Shape: the VM state is `vm`; `vm.A` is the register file, `vm.u` the')
out.push(' * instruction pointer, `vm.S` the cell boundary, `vm.o` the enclosing frame.')
out.push(' * Operand reads (`J` u16, `L` u8, `K` u24) are replaced by the literal')
out.push(' * values this instruction carries, so a line can be executed as-is.')
out.push(' *')
out.push(` *   bytecode      ${disasm.bytecodeBytes} bytes`)
out.push(` *   instructions  ${instructions.length}`)
out.push(` *   functions     ${fnDoc.functions.length}`)
out.push(' *')
out.push(' * Generated by scripts/10-decompile-faithful.mjs — do not edit by hand.')
out.push(' */')
out.push('')

for (const fn of fnDoc.functions) {
  const body = instructions.filter((i) => i.at >= fn.start && i.at < fn.end)
  out.push(`// fn #${fn.id}  entry ${String(fn.start)}  ${fn.instructionCount} instructions  ${fn.calledVia.join('/') || 'bootstrap'}`)
  out.push(`function fn_${fn.id}(vm) {`)
  for (const ins of body) {
    const spec = byOpcode.get(ins.opcode)
    const label = spec?.mnemonic ?? `op${ins.opcode}`
    const code = renderInstruction(ins)
    // Invoke the inlined handler with the VM state, exactly as `C[opcode](vm)`
    // does, so each instruction gets its own scope like the real dispatcher.
    out.push(`  /* @${ins.at} */ (${code})(vm)   // ${label}`)
  }
  out.push('}')
  out.push('')
}

fs.mkdirSync(OUT, { recursive: true })
fs.writeFileSync(path.join(OUT, 'decompiled-faithful.js'), out.join('\n') + '\n')

const bytes = fs.statSync(path.join(OUT, 'decompiled-faithful.js')).size
console.log(`instructions inlined  ${instructions.length}`)
console.log(`functions             ${fnDoc.functions.length}`)
console.log(`output                ${path.join(OUT, 'decompiled-faithful.js')} (${bytes} bytes)`)
