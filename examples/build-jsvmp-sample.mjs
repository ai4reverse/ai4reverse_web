#!/usr/bin/env node
/**
 * Regenerate `jsvmp-sample.js`.
 *
 * The sample is a real, deterministic JSVMP interpreter produced by the
 * platform's own builder (obfuscated opcode cipher + encoded constant indices).
 * Re-run this script after changing `tools/jsvmp/`:
 *
 *   node examples/build-jsvmp-sample.mjs
 */
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { buildVM, buildSampleProgram } from '../tools/jsvmp/index.js'

const vm = buildVM(buildSampleProgram(), { seed: 2026, name: '__vmp_run', obfuscate: true })

const header = `// Generated by examples/build-jsvmp-sample.mjs — do not edit by hand.
// A JSVMP (JavaScript virtual machine protection) interpreter: an obfuscated
// dispatch loop executes an encoded bytecode program. Analyzing this sample with
// \`instrumentation: { jsvmp: true }\` records opcode-level trace events.
`
const footer = `
console.log('vm result:', __vmp_run());
`

const target = fileURLToPath(new URL('./jsvmp-sample.js', import.meta.url))
await writeFile(target, `${header}${vm.code}${footer}`, 'utf8')
console.log(`wrote ${target} (${vm.opcodes.length} opcodes, ${vm.bytecode.length} instructions)`)
