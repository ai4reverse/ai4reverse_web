#!/usr/bin/env node
/**
 * Regenerate examples/suite/15-hybrid-ransomware-jsvmp/sample.js.
 *
 * The stage is driven by a JSVMP-protected VM: the bytecode builds the
 * encryption profile (cipher, round budget, target set, checksum) and the host
 * code around it performs the AES-GCM staging, ransom note and key exfiltration.
 */
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { buildVM } from '../../../tools/jsvmp/index.js'

/** Readable VM program: builds the stage configuration object in the VM. */
function buildStageProgram() {
  const program = []
  const emit = (op, ...args) => {
    program.push({ op, args })
    return program.length - 1
  }

  emit('NEW_OBJ')

  emit('DUP')
  emit('PUSH', 7)
  emit('SET_PROP', 'rounds')
  emit('POP')

  emit('DUP')
  emit('PUSH', 'aes-256-gcm')
  emit('SET_PROP', 'cipher')
  emit('POP')

  emit('DUP')
  emit('PUSH', 'Q4-finance')
  emit('SET_PROP', 'target')
  emit('POP')

  emit('DUP')
  emit('PUSH', 0)
  emit('SET_PROP', 'i')
  emit('POP')

  emit('DUP')
  emit('PUSH', 0)
  emit('SET_PROP', 'checksum')
  emit('POP')

  const loopStart = program.length
  emit('DUP')
  emit('GET_PROP', 'i')
  emit('PUSH', 7)
  emit('LT')
  const exitJump = emit('JMP_IF_NOT', 0)

  // checksum += i * 13
  emit('DUP')
  emit('DUP')
  emit('GET_PROP', 'checksum')
  emit('GET_PROP', 'i')
  emit('PUSH', 13)
  emit('MUL')
  emit('ADD')
  emit('SET_PROP', 'checksum')
  emit('POP')

  // i += 1
  emit('DUP')
  emit('DUP')
  emit('GET_PROP', 'i')
  emit('PUSH', 1)
  emit('ADD')
  emit('SET_PROP', 'i')
  emit('POP')

  emit('JMP', loopStart)
  program[exitJump].args = [program.length]
  emit('HALT')
  return program
}

const directory = fileURLToPath(new URL('./', import.meta.url))
const vm = buildVM(buildStageProgram(), { seed: 1515, name: '__stage_vm', obfuscate: true })

