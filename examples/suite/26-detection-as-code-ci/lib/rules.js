/**
 * Detection-as-code rule generation, rendering, parsing and matching.
 *
 * One analysed sample yields one *detection unit*: a YARA rule for content
 * matching plus a Sigma rule for behavioural matching. Both artefacts are
 * rendered as text, parsed back from disk, and then used to decide coverage, so
 * a rule only counts once it has survived a round trip through its own file.
 */

const PRIORITY_CATEGORIES = Object.freeze([
  ['urls', 3],
  ['telegram', 2],
  ['base64', 2],
  ['discordWebhooks', 1],
  ['wallets', 1],
  ['mutexes', 1],
  ['shellCommands', 1],
])

const MIN_STRING_LENGTH = 8
const MAX_STRINGS = 4

const slugify = (value) =>
  String(value)
    .replace(/\.[a-z0-9]+$/i, '')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase()

const escapeYara = (value) => String(value).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\r?\n/g, '\\n')

const unescapeYara = (value) => String(value).replace(/\\(["\\n])/g, (_, char) => (char === 'n' ? '\n' : char))

const unquote = (value) => {
  const text = String(value).trim()
  if (text.length >= 2 && text.startsWith('"') && text.endsWith('"')) return text.slice(1, -1)
  return text
}

/** Pick the most specific indicator strings for a sample, in a stable order. */
export function selectStrings(report) {
  const iocs = report?.static?.iocs ?? {}
  const seen = new Set()
  const values = []
  for (const [category, limit] of PRIORITY_CATEGORIES) {
    const list = iocs[category]
    if (!Array.isArray(list)) continue
    let taken = 0
    for (const entry of list) {
      if (taken >= limit) break
      const value = typeof entry?.value === 'string' ? entry.value : null
      if (!value || value.length < MIN_STRING_LENGTH || seen.has(value)) continue
      seen.add(value)
      values.push(value)
      taken += 1
      if (values.length >= MAX_STRINGS) return values
    }
  }
  return values
}

function selectBehaviours(report) {
  const techniques = Array.isArray(report?.static?.techniques) ? report.static.techniques.slice(0, 2) : []
  const stages = (report?.dynamic?.behavior?.killChain ?? []).map((stage) => stage?.stage).filter(Boolean).slice(0, 2)
  const suspiciousTld = ['urls', 'domains'].some((category) =>
    (report?.static?.iocs?.[category] ?? []).some((entry) => entry?.suspiciousTld === true),
  )
  return { techniques, stages, suspiciousTld }
}

/**
 * Build the detection unit for one sample.
 *
 * @param {{relative: string, sha256: string, verdict: string, score: number, report: object}} sample
 */
export function buildDetectionUnit(sample) {
  const slug = slugify(sample.relative) || 'SAMPLE'
  const name = `JS_${slug}_${sample.sha256.slice(0, 8).toUpperCase()}`
  const strings = selectStrings(sample.report)
  const behaviours = selectBehaviours(sample.report)
  const condition = strings.length === 0 ? null : strings.length === 1 ? 'any of them' : strings.length === 2 ? 'all of them' : '2 of them'
  const selections = []
  const urls = sample.report?.static?.iocs?.urls ?? []
  for (const entry of urls.slice(0, 2)) {
    const host = entry?.host ?? null
    if (host) selections.push({ name: `selection_host_${selections.length + 1}`, field: 'url', modifier: 'contains', values: [host] })
    else if (entry?.value) selections.push({ name: `selection_url_${selections.length + 1}`, field: 'url', modifier: 'contains', values: [entry.value.slice(0, 80)] })
  }
  for (const technique of behaviours.techniques) {
    selections.push({ name: `selection_technique_${selections.length + 1}`, field: 'technique', modifier: 'contains', values: [technique] })
  }
  if (behaviours.suspiciousTld) {
    selections.push({ name: `selection_tld_${selections.length + 1}`, field: 'suspiciousTld', modifier: 'equals', values: ['true'] })
  }
  if (sample.report?.tracing?.jsvmp?.detected === true) {
    selections.push({ name: `selection_jsvmp_${selections.length + 1}`, field: 'action', modifier: 'contains', values: ['jsvmp.detected'] })
  }
  return {
    name,
    id: `dc-${sample.sha256.slice(0, 12)}`,
    level: sample.verdict === 'malicious' ? 'high' : 'medium',
    reference: sample.relative,
    sha256: sample.sha256,
    score: sample.score,
    strings: strings.map((value, index) => ({ id: `$s${index + 1}`, value })),
    condition,
    selections,
    sigmaCondition: selections.length === 0 ? null : '1 of selection_*',
  }
}

/** Render a detection unit as a YARA rule. */
export function renderYara(unit) {
  const lines = [
    `/* Generated by ai4reverse detection-as-code from ${unit.reference}. */`,
    `rule ${unit.name}`,
    '{',
    '  meta:',
    '    author = "ai4reverse detection-as-code"',
    `    description = "Indicators recovered from ${unit.reference}"`,
    `    reference = "sample:${unit.reference}"`,
    `    sample_sha256 = "${unit.sha256}"`,
    `    severity = "${unit.level}"`,
    '  strings:',
  ]
  for (const entry of unit.strings) lines.push(`    ${entry.id} = "${escapeYara(entry.value)}" ascii nocase`)
  lines.push('  condition:')
  lines.push(`    ${unit.condition}`)
  lines.push('}')
  return `${lines.join('\n')}\n`
}

/** Render a detection unit as a Sigma rule (YAML flow sequences). */
export function renderSigma(unit) {
  const lines = [
    `title: JS behaviour ${unit.name}`,
    `id: ${unit.id}`,
    'status: experimental',
    `description: Behavioural detection generated from ${unit.reference}`,
    `level: ${unit.level}`,
    'tags:',
    `  - js-detection-as-code`,
    'logsource:',
    '  product: browser',
    '  service: javascript',
    'detection:',
  ]
  for (const selection of unit.selections) {
    lines.push(`  ${selection.name}:`)
    lines.push(`    ${selection.field}|${selection.modifier}: ${JSON.stringify(selection.values)}`)
  }
  lines.push(`  condition: ${unit.sigmaCondition}`)
  lines.push('falsepositives:')
  lines.push('  - Unknown legitimate software sharing the recovered indicators')
  return `${lines.join('\n')}\n`
}

/** Parse a YARA rule rendered by this module (subset: strings + simple condition). */
export function parseYara(text) {
  const source = String(text)
  const header = /rule\s+([A-Za-z_][A-Za-z0-9_]*)\s*\{/.exec(source)
  if (!header) throw new Error('YARA rule is missing a `rule <name> {` header')
  const metaBlock = /meta:\s*\n([\s\S]*?)\n\s*strings:/.exec(source)
  const meta = {}
  if (metaBlock) {
    for (const match of metaBlock[1].matchAll(/([A-Za-z_][A-Za-z0-9_]*)\s*=\s*"((?:[^"\\]|\\.)*)"/g)) {
      meta[match[1]] = unescapeYara(match[2])
    }
  }
  const stringsHeader = /strings:\s*\n/.exec(source)
  if (!stringsHeader) throw new Error('YARA rule is missing a `strings:` block')
  const tail = source.slice(stringsHeader.index + stringsHeader[0].length)
  const conditionAt = /(?:^|\n)\s*condition:/.exec(tail)
  if (!conditionAt) throw new Error('YARA rule is missing a `condition:` expression')
  const stringsSection = tail.slice(0, conditionAt.index)
  const strings = [...stringsSection.matchAll(/(\$[A-Za-z_][A-Za-z0-9_]*)\s*=\s*"((?:[^"\\]|\\.)*)"([^\n]*)/g)].map((match) => ({
    id: match[1],
    value: unescapeYara(match[2]),
    flags: match[3].trim(),
  }))
  if (strings.length === 0) throw new Error('YARA rule declares no string patterns')
  const conditionMatch = /condition:\s*([^\n]+)/.exec(tail)
  if (!conditionMatch) throw new Error('YARA rule is missing a `condition:` expression')
  const condition = conditionMatch[1].trim()
  if (!/^(?:any of them|all of them|\d+ of them)$/i.test(condition)) {
    throw new Error(`unsupported YARA condition "${condition}" (supported: any/all/N of them)`)
  }
  return { name: header[1], meta, strings, condition, kind: 'yara' }
}

function parseScalarOrList(raw) {
  const text = String(raw).trim()
  if (text.startsWith('[') && text.endsWith(']')) {
    const parsed = JSON.parse(text.replace(/'/g, '"'))
    return parsed.map(String)
  }
  return [unquote(text)]
}

/** Parse a Sigma rule rendered by this module (subset: selections + quantifier). */
export function parseSigma(text) {
  const lines = String(text).split(/\r?\n/)
  const rule = { title: '', id: '', level: 'medium', tags: [], selections: [], condition: '', kind: 'sigma' }
  let inDetection = false
  let current = null
  let pendingField = null
  for (const line of lines) {
    if (line.trim().length === 0 || line.trim().startsWith('#')) continue
    const indent = line.length - line.trimStart().length
    const body = line.trim()
    if (indent === 0) {
      inDetection = body === 'detection:'
      current = null
      pendingField = null
      const top = /^([a-z_]+):\s*(.*)$/.exec(body)
      if (!top) continue
      if (top[1] === 'title') rule.title = unquote(top[2])
      if (top[1] === 'id') rule.id = unquote(top[2])
      if (top[1] === 'level') rule.level = unquote(top[2])
      continue
    }
    if (!inDetection) continue
    if (indent === 2 && body.startsWith('- ')) {
      rule.tags.push(unquote(body.slice(2)))
      continue
    }
    if (indent === 2) {
      if (body.startsWith('condition:')) {
        rule.condition = unquote(body.slice('condition:'.length).trim())
        current = null
        pendingField = null
        continue
      }
      const key = body.replace(/:\s*$/, '')
      current = { name: key, field: null, modifier: 'equals', values: [] }
      rule.selections.push(current)
      continue
    }
    if (!current) continue
    if (indent >= 4 && body.startsWith('- ')) {
      if (!pendingField) throw new Error(`selection "${current.name}" has a list item without a field`)
      current.values.push(unquote(body.slice(2)))
      continue
    }
    const colon = body.indexOf(':')
    if (colon < 0) continue
    const key = body.slice(0, colon).trim()
    const [field, modifier = 'equals'] = key.split('|')
    const raw = body.slice(colon + 1).trim()
    pendingField = field
    current.field = field
    current.modifier = modifier
    current.values = raw.length > 0 ? parseScalarOrList(raw) : []
  }
  if (rule.selections.length === 0) throw new Error('Sigma rule declares no selections')
  if (!rule.condition) throw new Error('Sigma rule is missing a condition')
  if (!/^(?:1 of selection_\*|any of them|all of them)$/i.test(rule.condition)) {
    throw new Error(`unsupported Sigma condition "${rule.condition}" (supported: 1 of selection_*, any/all of them)`)
  }
  return rule
}

/** Count string matches for a YARA rule over one haystack. */
export function matchYara(rule, haystack) {
  const text = String(haystack)
  const lower = text.toLowerCase()
  let matched = 0
  for (const entry of rule.strings) {
    const nocase = /nocase/i.test(entry.flags ?? '')
    const found = nocase ? lower.includes(entry.value.toLowerCase()) : text.includes(entry.value)
    if (found) matched += 1
  }
  const condition = rule.condition.toLowerCase()
  if (condition === 'any of them') return matched >= 1
  if (condition === 'all of them') return matched === rule.strings.length
  const required = Number(/(\d+) of them/.exec(condition)?.[1] ?? 1)
  return matched >= required
}

/** Evaluate a Sigma rule against a flat sample record. */
export function matchSigma(rule, record) {
  const outcomes = new Map()
  for (const selection of rule.selections) {
    const actual = String(record[selection.field] ?? '').toLowerCase()
    const hit = selection.values.some((value) => {
      const expected = String(value).toLowerCase()
      if (selection.modifier === 'contains') return actual.includes(expected)
      return actual.split(/\s+/).includes(expected)
    })
    outcomes.set(selection.name, hit)
  }
  const condition = rule.condition.toLowerCase()
  if (condition === 'any of them' || condition === '1 of selection_*') {
    return [...outcomes.values()].some(Boolean)
  }
  return [...outcomes.values()].every(Boolean)
}
