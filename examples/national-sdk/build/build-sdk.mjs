/**
 * Protected build pipeline.
 *
 * One seed drives every randomised decision: the static white-box key, the VM
 * opcode permutation and blob encryption, the export-name mapping, the
 * obfuscation passes and their parameters. Two seeds therefore produce two
 * functionally identical bundles with different tables, opcode maps, string
 * masks, identifiers and control-flow shapes.
 *
 *   node build/build-sdk.mjs --seed 1001 --seed 1002
 *   node build/build-sdk.mjs --seeds 1001-1004 --no-verify
 *
 * The output lands in `dist/`; `manifest.json` records the seed, hash, size and
 * VM instruction count of every artifact.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { createPrng } from '../src/core/prng.js'
import { fromHex, toHex, utf8ToBytes } from '../src/core/bytes.js'
import { kdfSm3, sm3 } from '../src/core/hash.js'
import { createWhiteboxSpn } from '../src/core/whitebox/spn-wb.js'
import { buildSigningBlob, shuffleHandlerIds } from '../src/vm/index.js'
import { bundle } from './bundle.mjs'
import { obfuscate } from './obfuscate.mjs'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const CONFIG_PATH = path.join(ROOT, 'build/generated/config.js')

/**
 * Derive the VM key exactly as the runtime does: through the SPN instance the
 * bundle will create from its embedded build salt and white-box key.
 * @param {string} buildSalt
 * @param {string} spnKeyHex
 */
export function deriveVmKey(buildSalt, spnKeyHex) {
  const spn = createWhiteboxSpn({ seed: `${buildSalt}::device-spn`, key: fromHex(spnKeyHex) })
  const iv = kdfSm3(utf8ToBytes('nsdk/vm/key/signing'), 'vm-key-iv', 16)
  return spn.keystream(iv, 32)
}

/**
 * @param {{seed: string|number, root?: string, outDir?: string, minify?: boolean}} options
 * @returns {Promise<{seed: string, file: string, code: string, manifest: object}>}
 */
export async function buildSdk(options) {
  const root = options.root ?? ROOT
  const seed = String(options.seed)
  const outDir = options.outDir ?? path.join(root, 'dist')
  const prng = createPrng(`nsdk-build:${seed}`, 'build')

  const spnKeyHex = prng.hex(32)
  const buildSalt = prng.hex(8)
  const vmKey = deriveVmKey(buildSalt, spnKeyHex)
  const perm = shuffleHandlerIds(vmKey)
  const { blob: vmBlob, program } = buildSigningBlob({ key: vmKey, perm })

  const config = {
    seed,
    buildSalt,
    spnKeyHex,
    vmBlob,
  }
  await mkdir(path.dirname(CONFIG_PATH), { recursive: true })
  await writeFile(
    CONFIG_PATH,
    `// Generated by build/build-sdk.mjs for seed ${seed}. Do not edit.\nexport const BUILD_CONFIG = ${JSON.stringify(config, null, 2)}\n`,
  )

  const { code: unminified, files } = await bundle({
    entry: 'build/entry.js',
    root,
    seed: `bundle:${seed}`,
  })
  const protectedCode = obfuscate(unminified, `obfuscate:${seed}`)
  await mkdir(outDir, { recursive: true })
  const file = path.join(outDir, `nsdk-${seed}.js`)
  await writeFile(file, protectedCode)

  const manifest = {
    seed,
    file: path.relative(root, file),
    bytes: Buffer.byteLength(protectedCode, 'utf8'),
    sha256: toHex(sm3(utf8ToBytes(protectedCode))),
    spnKeyId: toHex(sm3(utf8ToBytes(spnKeyHex))).slice(0, 16),
    buildSalt,
    vm: {
      instructions: program.instructions.length,
      perm,
      constantCount: program.consts.length,
      blobBytes: Buffer.byteLength(JSON.stringify(vmBlob)),
    },
    modules: files.length,
    generatedAt: new Date().toISOString(),
  }
  return { seed, file, code: protectedCode, manifest }
}

/**
 * Build several variants and write a manifest.
 * @param {{seeds: Array<string|number>, root?: string, outDir?: string}} options
 */
export async function buildVariants(options) {
  const root = options.root ?? ROOT
  const outDir = options.outDir ?? path.join(root, 'dist')
  const results = []
  for (const seed of options.seeds) results.push(await buildSdk({ seed, root, outDir }))
  const manifestPath = path.join(outDir, 'manifest.json')
  let existing = { builds: [] }
  try {
    existing = JSON.parse(await readFile(manifestPath, 'utf8'))
  } catch {
    /* first build */
  }
  const bySeed = new Map(existing.builds.map((entry) => [entry.seed, entry]))
  for (const result of results) bySeed.set(result.seed, result.manifest)
  await mkdir(outDir, { recursive: true })
  await writeFile(
    manifestPath,
    `${JSON.stringify({ generatedAt: new Date().toISOString(), builds: Array.from(bySeed.values()) }, null, 2)}\n`,
  )
  return results
}

/** @param {string[]} argv */
function parseArgs(argv) {
  const seeds = []
  let outDir = null
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (arg === '--seed') seeds.push(argv[++index])
    else if (arg === '--seeds') {
      const spec = argv[++index] ?? '1001'
      const range = /^(\d+)-(\d+)$/.exec(spec)
      if (range) {
        for (let value = Number(range[1]); value <= Number(range[2]); value += 1) seeds.push(String(value))
      } else {
        seeds.push(...spec.split(',').map((value) => value.trim()).filter(Boolean))
      }
    } else if (arg === '--out') outDir = argv[++index]
  }
  return { seeds: seeds.length > 0 ? seeds : ['1001'], outDir }
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (invokedDirectly) {
  const args = parseArgs(process.argv.slice(2))
  const results = await buildVariants({ seeds: args.seeds, outDir: args.outDir })
  for (const result of results) {
    console.log(`${result.manifest.file}\t${result.manifest.bytes} bytes\t${result.manifest.sha256.slice(0, 16)}\tvm:${result.manifest.vm.instructions} insns`)
  }
}
